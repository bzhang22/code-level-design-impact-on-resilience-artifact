#!/usr/bin/env python3
"""
Regenerate the paper's main tables from results/processed/summary.csv.

For every program we pair its base and variant rows, report SDC probability
and dynamic instruction count side by side, and compute the two-proportion
z-statistic that the paper uses (Section IV). Outputs, under results/tables/:

  controlled_pairs.csv / .tex   the six controlled single-difference pairs
  table5_applications.csv / .tex the Case Studies table (paper Table V)

Nothing here is fabricated: the SDC percentages come straight from the counts
aggregated by aggregate_results.py.

Usage:
  python3 scripts/generate_tables.py --summary results/processed/summary.csv \
                                     --output results/tables
"""
import argparse
import csv
import math
import os


def two_proportion_z(s1, n1, s2, n2):
    p1, p2 = s1 / n1, s2 / n2
    p = (s1 + s2) / (n1 + n2)
    denom = math.sqrt(p * (1 - p) * (1.0 / n1 + 1.0 / n2))
    if denom == 0:
        return 0.0
    return (p1 - p2) / denom


def load_pairs(summary_path):
    rows = []
    with open(summary_path, newline="") as fh:
        rows = list(csv.DictReader(fh))
    pairs = {}
    for r in rows:
        key = (r["group"], r["program"])
        pairs.setdefault(key, {})[r["role"]] = r
    return pairs


def di_str(di):
    di = float(di)
    if di <= 0:
        return "--"
    exp = int(math.floor(math.log10(di)))
    mant = di / (10 ** exp)
    return "%.1f\\times10^{%d}" % (mant, exp)


def emit(group_filter, pairs, order, out_csv, out_tex, title, caption):
    recs = []
    for prog in order:
        key = (group_filter, prog)
        if key not in pairs or "base" not in pairs[key] or "variant" not in pairs[key]:
            continue
        b, v = pairs[key]["base"], pairs[key]["variant"]
        nb, nv = int(b["num_injections"]), int(v["num_injections"])
        sb, sv = int(b["sdc_count"]), int(v["sdc_count"])
        z = two_proportion_z(sb, nb, sv, nv)
        recs.append({
            "program": prog,
            "insight": b["insight"],
            "mechanism": b["mechanism"],
            "sdc_base_pct": float(b["sdc_probability_pct"]),
            "sdc_variant_pct": float(v["sdc_probability_pct"]),
            "di_base": int(b["dynamic_instruction_count"]),
            "di_variant": int(v["dynamic_instruction_count"]),
            "n_base": nb, "n_variant": nv,
            "z": z,
            "significant_0.05": "yes" if abs(z) >= 1.96 else "no",
            "no_added_work": "yes" if int(v["dynamic_instruction_count"]) <= int(b["dynamic_instruction_count"]) else "no",
        })

    with open(out_csv, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(recs[0].keys()))
        w.writeheader()
        for r in recs:
            w.writerow(r)

    with open(out_tex, "w") as fh:
        fh.write("%% %s -- generated by generate_tables.py\n" % title)
        fh.write("\\begin{tabular}{@{}llcccc@{}}\n\\toprule\n")
        fh.write("\\textbf{Program} & \\textbf{Insight} & "
                 "\\textbf{SDC\\% (b$\\to$v)} & \\textbf{DI (b$\\to$v)} & "
                 "$z$ & \\textbf{No added work?} \\\\\n\\midrule\n")
        for r in recs:
            fh.write("%s & %s (\\#%s) & $%.1f \\to %.1f$ & $%s{\\to}%s$ & $%.1f$ & %s \\\\\n" % (
                r["program"].replace("_", "\\_"), r["mechanism"], r["insight"],
                r["sdc_base_pct"], r["sdc_variant_pct"],
                di_str(r["di_base"]), di_str(r["di_variant"]),
                r["z"], r["no_added_work"]))
        fh.write("\\bottomrule\n\\end{tabular}\n")

    print("wrote %s and %s (%d programs)" % (out_csv, out_tex, len(recs)))
    return recs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", default="results/processed/summary.csv")
    ap.add_argument("--output", default="results/tables")
    args = ap.parse_args()
    os.makedirs(args.output, exist_ok=True)
    pairs = load_pairs(args.summary)

    controlled_order = ["verdict_encoding", "loop_invariant", "branch_selection",
                        "conditional_write", "bounded_lookup", "masked_accumulator"]
    apps_order = ["running_maximum", "dna_motif_search", "string_search", "dijkstra",
                  "histogram", "transform_sum", "weighted_map", "threshold_sum",
                  "record_scan", "blackscholes"]

    emit("controlled_pairs", pairs, controlled_order,
         os.path.join(args.output, "controlled_pairs.csv"),
         os.path.join(args.output, "controlled_pairs.tex"),
         "Controlled single-difference pairs",
         "Controlled pairs")
    emit("applications", pairs, apps_order,
         os.path.join(args.output, "table5_applications.csv"),
         os.path.join(args.output, "table5_applications.tex"),
         "Case studies (paper Table V)",
         "Applications")


if __name__ == "__main__":
    main()
